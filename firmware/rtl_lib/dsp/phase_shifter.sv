      end else begin
         // 2-stage alignment delay, then present alongside cos_val/sin_val.
         i_align1 <= i_in_r;   i_align2 <= i_align1;   i_stage1 <= i_align2;
         q_align1 <= q_in_r;   q_align2 <= q_align1;   q_stage1 <= q_align2;
