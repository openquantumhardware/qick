   //! Data / coefficient width (Q1.15, HW = 16).
   parameter int DW  = 16,
   //! Phase word width (HW = 16).
   parameter int PW  = 16,
   //! LUT address width (HW = 11 -> 2048 entries).
   parameter int LAW = 11
