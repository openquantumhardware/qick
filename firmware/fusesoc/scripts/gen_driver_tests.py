#!/usr/bin/env python3
"""Auto-generate driver/tests/ (conftest + register-layer pytest) from the
PeakRDL-generated package. Introspects the reg model so tests stay in sync with
the RDL (reset values, per-field roundtrip, register independence).

Usage: python3 scripts/gen_driver_tests.py <ip_name>
"""
import sys
from pathlib import Path

CONFTEST = '''\
import sys
from pathlib import Path

# driver/tests/ -> ../../rdl/ contains {ip}_regmap_pkg/
_RDL_DIR = Path(__file__).resolve().parents[2] / "rdl"
if str(_RDL_DIR) not in sys.path:
    sys.path.insert(0, str(_RDL_DIR))
'''

TEST_HEADER = '''\
# AUTO-GENERATED by scripts/gen_driver_tests.py — edit freely, but note that
# re-running the generator OVERWRITES this file. Add hand-written cases in a
# separate test_{ip}_extra.py.
import pytest
from {ip}_regmap_pkg.reg_model import RegModel
from {ip}_regmap_pkg.sim import Simulator
from {ip}_regmap_pkg.lib import NormalCallbackSet


def make_sim_regs():
    sim = Simulator(address=0)
    return RegModel(
        callbacks=NormalCallbackSet(
            read_callback=sim.read,
            write_callback=sim.write,
            read_block_callback=sim.read_block,
            write_block_callback=sim.write_block,
        )
    )


@pytest.fixture
def regs():
    return make_sim_regs()
'''


def introspect(ip):
    """Return [(reg_name, address, [(field_name, width, is_sw_writable)])]."""
    rdl_dir = Path("cores/ip") / ip / "rdl"
    sys.path.insert(0, str(rdl_dir))
    mod = __import__(f"{ip}_regmap_pkg.reg_model", fromlist=["RegModel"])
    RegModel = mod.RegModel
    sim_mod = __import__(f"{ip}_regmap_pkg.sim", fromlist=["Simulator"])
    lib_mod = __import__(f"{ip}_regmap_pkg.lib", fromlist=["NormalCallbackSet"])
    sim = sim_mod.Simulator(address=0)
    model = RegModel(callbacks=lib_mod.NormalCallbackSet(
        read_callback=sim.read, write_callback=sim.write,
        read_block_callback=sim.read_block, write_block_callback=sim.write_block))
    regs = []
    for reg in model.get_registers():
        rname = reg.inst_name
        # Read-only registers do NOT expose writable_fields -> default to [].
        writable_names = {f.inst_name for f in getattr(reg, "writable_fields", [])}
        # 'fields' may be absent on some register types; fall back to the union
        # of readable_fields and writable_fields.
        if hasattr(reg, "fields"):
            all_fields = list(reg.fields)
        else:
            seen, all_fields = set(), []
            for src in ("readable_fields", "writable_fields"):
                for f in getattr(reg, src, []):
                    if f.inst_name not in seen:
                        seen.add(f.inst_name)
                        all_fields.append(f)
        fields = [(f.inst_name, f.width, f.inst_name in writable_names)
                  for f in all_fields]
        regs.append((rname, reg.address, fields))
    return regs

def emit(ip, regs):
    lines = [TEST_HEADER.format(ip=ip)]

    # Reset values.
    lines.append("\ndef test_reset_values(regs):")
    for rname, _addr, fields in regs:
        for fname, _w, writable in fields:
            if writable:
                lines.append(f"    assert regs.{rname}.{fname}.read() == 0")
    lines.append("")

    # Offsets.
    lines.append("\ndef test_register_offsets(regs):")
    for rname, addr, _f in regs:
        lines.append(f"    assert regs.{rname}.address == {hex(addr)}")
    lines.append("")

    # Per-field roundtrip.
    lines.append("\ndef test_field_roundtrip(regs):")
    for rname, _addr, fields in regs:
        for fname, width, writable in fields:
            if not writable:
                continue
            val = (1 << width) - 1 if width < 32 else 0xDEADBEEF
            lines.append(f"    regs.{rname}.{fname}.write({hex(val)})")
            lines.append(f"    assert regs.{rname}.{fname}.read() == {hex(val)}")
            lines.append(f"    regs.{rname}.{fname}.write(0)")
    lines.append("")

    # Independence.
    lines.append("\ndef test_register_independence(regs):")
    writes = []
    for rname, _addr, fields in regs:
        for fname, width, writable in fields:
            if not writable:
                continue
            val = (1 << width) - 1 if width < 32 else 0xABCD
            writes.append((rname, fname, val))
    for rname, fname, val in writes:
        lines.append(f"    regs.{rname}.{fname}.write({hex(val)})")
    for rname, fname, val in writes:
        lines.append(f"    assert regs.{rname}.{fname}.read() == {hex(val)}")
    lines.append("")

    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        print("usage: gen_driver_tests.py <ip_name>")
        sys.exit(1)
    ip = sys.argv[1]
    tdir = Path("cores/ip") / ip / "driver" / "tests"
    tdir.mkdir(parents=True, exist_ok=True)

    (tdir / "conftest.py").write_text(CONFTEST.format(ip=ip))

    regs = introspect(ip)
    (tdir / f"test_{ip}_regs.py").write_text(emit(ip, regs))
    print(f"  ✓ wrote {tdir}/conftest.py")
    print(f"  ✓ wrote {tdir}/test_{ip}_regs.py  ({len(regs)} registers)")


if __name__ == "__main__":
    main()
